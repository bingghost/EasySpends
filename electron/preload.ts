const api = {
  getDashboard: () => ipcRenderer.invoke('dashboard:get') as Promise<DashboardData>,
  getAccounts: (includeArchived = false) => ipcRenderer.invoke('accounts:list', includeArchived) as Promise<Account[]>,
  createAccount: (input: CreateAccountInput) => ipcRenderer.invoke('accounts:create', input) as Promise<Account>,
  updateAccount: (input: UpdateAccountInput) => ipcRenderer.invoke('accounts:update', input) as Promise<Account>,
  archiveAccount: (id: number) => ipcRenderer.invoke('accounts:archive', id) as Promise<AccountMutationResult>,
  restoreAccount: (id: number) => ipcRenderer.invoke('accounts:restore', id) as Promise<AccountMutationResult>,
  deleteAccount: (id: number) => ipcRenderer.invoke('accounts:delete', id) as Promise<AccountMutationResult>,
  getTransfers: (limit?: number) => ipcRenderer.invoke('transfers:list', limit) as Promise<Transfer[]>,
  createTransfer: (input: NewTransferInput) => ipcRenderer.invoke('transfers:create', input) as Promise<DashboardData>,
  deleteTransfer: (id: number) => ipcRenderer.invoke('transfers:delete', id) as Promise<DashboardData>,
  getLedgerEntries: (options: LedgerListOptions = {}) => ipcRenderer.invoke('ledger:list', options) as Promise<LedgerEntry[]>,
  getCashflowChart: (period: ChartPeriod = 'month') => ipcRenderer.invoke('cashflow:chart', period) as Promise<CashflowChartData>,
  getAssetAnalytics: () => ipcRenderer.invoke('assets:analytics') as Promise<AssetAnalytics>,
  getBudgets: (month?: string) => ipcRenderer.invoke('budgets:list', month) as Promise<BudgetSummary>,
  saveBudget: (input: SaveBudgetInput) => ipcRenderer.invoke('budgets:save', input) as Promise<BudgetSummary>,
  deleteBudget: (id: number) => ipcRenderer.invoke('budgets:delete', id) as Promise<BudgetSummary>,
  getRecurringRules: (includeDisabled = true) => ipcRenderer.invoke('recurring:list', includeDisabled) as Promise<RecurringRule[]>,
  saveRecurringRule: (input: SaveRecurringRuleInput) => ipcRenderer.invoke('recurring:save', input) as Promise<RecurringRule>,
  deleteRecurringRule: (id: number) => ipcRenderer.invoke('recurring:delete', id) as Promise<void>,
  runRecurringDue: () => ipcRenderer.invoke('recurring:run-now') as Promise<RecurringRunResult[]>,
  previewImport: (input: ImportTransactionsInput) => ipcRenderer.invoke('imports:preview', input) as Promise<ImportPreview>,
  importTransactions: (input: ImportTransactionsInput) => ipcRenderer.invoke('imports:run', input) as Promise<ImportResult>,
  getImportHistory: (limit?: number) => ipcRenderer.invoke('imports:history', limit) as Promise<ImportBatch[]>,
  getNotificationSettings: () => ipcRenderer.invoke('notifications:get-settings') as Promise<NotificationSettings>,
  updateNotificationSettings: (input: UpdateNotificationSettingsInput) => ipcRenderer.invoke('notifications:update-settings', input) as Promise<NotificationSettings>,
  getNotificationHistory: (limit?: number) => ipcRenderer.invoke('notifications:list', limit) as Promise<NotificationEvent[]>,
  getCategories: (type?: TransactionType, includeArchived = false) =>
    ipcRenderer.invoke('categories:list', type, includeArchived) as Promise<Category[]>,
  createCategory: (input: CreateCategoryInput) =>
    ipcRenderer.invoke('categories:create', input) as Promise<Category>,
  updateCategory: (input: UpdateCategoryInput) =>
    ipcRenderer.invoke('categories:update', input) as Promise<Category>,
  archiveCategory: (id: number) =>
    ipcRenderer.invoke('categories:archive', id) as Promise<CategoryMutationResult>,
  restoreCategory: (id: number) =>
    ipcRenderer.invoke('categories:restore', id) as Promise<CategoryMutationResult>,
  deleteCategory: (id: number) =>
    ipcRenderer.invoke('categories:delete', id) as Promise<CategoryMutationResult>,
  getTransactions: (limit?: number) => ipcRenderer.invoke('transactions:list', limit) as Promise<Transaction[]>,
  createTransaction: (input: NewTransactionInput) => ipcRenderer.invoke('transactions:create', input) as Promise<DashboardData>,
  deleteTransaction: (id: number) => ipcRenderer.invoke('transactions:delete', id) as Promise<DashboardData>,
  openDataFolder: () => ipcRenderer.invoke('app:open-data-folder') as Promise<string>,
  getBackgroundSettings: () => ipcRenderer.invoke('background:get-settings') as Promise<BackgroundSettings>,
  updateBackgroundSettings: (input: UpdateBackgroundSettingsInput) => ipcRenderer.invoke('background:update-settings', input) as Promise<BackgroundSettings>,
  getSecurityStatus: () => ipcRenderer.invoke('security:get-status') as Promise<SecurityStatus>,
  chooseBackupPath: () => ipcRenderer.invoke('backup:choose-path') as Promise<string | null>,
  createBackup: (path?: string) => ipcRenderer.invoke('backup:create', path) as Promise<BackupResult>,
  chooseRestorePath: () => ipcRenderer.invoke('backup:choose-restore-path') as Promise<string | null>,
  restoreBackup: (path: string) => ipcRenderer.invoke('backup:restore', path) as Promise<BackupResult>
}

contextBridge.exposeInMainWorld('easySpends', api)

export type EasySpendsApi = typeof api
