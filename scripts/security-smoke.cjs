const assert = require('node:assert/strict')
const { createCipheriv, createDecipheriv, createHash, randomBytes } = require('node:crypto')
const { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')
const Database = require('better-sqlite3-multiple-ciphers')

const root = join('/tmp', `easyspends-security-${process.pid}`)
mkdirSync(root, { recursive: true })
const databasePath = join(root, 'secure.db')
const key = randomBytes(32)
const wrongKey = randomBytes(32)

const database = new Database(databasePath)
database.exec('CREATE TABLE ledger (id INTEGER PRIMARY KEY, amount_cents INTEGER NOT NULL)')
database.prepare('INSERT INTO ledger (amount_cents) VALUES (?)').run(12345)
database.rekey(key)
database.close()
assert.notEqual(readFileSync(databasePath).subarray(0, 15).toString(), 'SQLite format 3')

const reopened = new Database(databasePath)
reopened.key(key)
assert.equal(reopened.prepare('SELECT amount_cents FROM ledger WHERE id = 1').get().amount_cents, 12345)
reopened.close()

const wrong = new Database(databasePath)
wrong.key(wrongKey)
assert.throws(() => wrong.prepare('SELECT * FROM ledger').all(), /not a database|file is not a database/i)
wrong.close()

const MAGIC = Buffer.from('EASYSPENDS-BACKUP-V1\\0', 'utf8')
const nonce = randomBytes(12)
const backupKey = createHash('sha256').update(Buffer.concat([Buffer.from('EasySpends backup v1\\0'), key])).digest()
const cipher = createCipheriv('aes-256-gcm', backupKey, nonce)
const encrypted = Buffer.concat([cipher.update(readFileSync(databasePath)), cipher.final()])
const payload = Buffer.concat([MAGIC, nonce, cipher.getAuthTag(), encrypted])
const backupPath = join(root, 'backup.esb')
writeFileSync(backupPath, payload, { mode: 0o600 })
const decipher = createDecipheriv('aes-256-gcm', backupKey, nonce)
decipher.setAuthTag(payload.subarray(MAGIC.length + 12, MAGIC.length + 12 + 16))
const decrypted = Buffer.concat([decipher.update(payload.subarray(MAGIC.length + 12 + 16)), decipher.final()])
assert.deepEqual(decrypted, readFileSync(databasePath))
assert.equal(existsSync(backupPath), true)
rmSync(root, { recursive: true, force: true })
console.log(JSON.stringify({ status: 'passed', sqlite_file_encrypted: true, wrong_key_rejected: true, backup_authenticated: true }))
